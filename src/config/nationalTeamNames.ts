const trRegions = (() => {
  try {
    return new Intl.DisplayNames(['tr'], { type: 'region' });
  } catch {
    return null;
  }
})();

export function nationalTeamNameTr(name: string): string {
  const key = name.trim();
  if (OVERRIDES[key]) return OVERRIDES[key]!;
  const iso = ISO2[key];
  if (iso && trRegions) {
    try {
      const tr = trRegions.of(iso);
      if (tr && tr !== iso) return tr;
    } catch {
      // yedek: İngilizce ad
    }
  }
  return name;
}
